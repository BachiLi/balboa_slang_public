def make_scene():
    nx, ny = 37, 37
    sx, sy = 2.7, 2.7
    rock = make_rock()

    positions, triangles, dx, dy = make_cloth_grid(nx, ny, sx, sy)
    positions[:, 1] = rock['vertices'][:, 1].max() + 0.2
    edges, rest_lengths = make_cloth_constraints(nx, ny, dx, dy)

    return {
        'positions': positions.astype(np.float32),
        'velocities': np.zeros_like(positions),
        'inv_masses': np.ones(
            len(positions), dtype=np.float32),

        'constraint_edges': edges,
        'rest_lengths': rest_lengths,

        'triangles': triangles,
        'cloth_grid_size': (nx, ny),
        'spacing': (dx, dy),

        'collision_mesh': rock,

        'planes': np.array([
            [0, 1, 0, 0],
        ], dtype=np.float32),
        'spheres': np.zeros((0, 4), dtype=np.float32),

        'collision_distance': 0.025,
        'contact_margin': 0.035,
        'static_friction': 0.5,
        'kinetic_friction': 0.3,

        'substeps': 8,
        'iterations': 12,

        'cam_pos': (3.3, 2.6, -4.5),
        'cam_target': (0.0, 0.9, 0.0),
        'cam_up': (0.0, 1.0, 0.0),
    }
